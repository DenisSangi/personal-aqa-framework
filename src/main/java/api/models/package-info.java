/**
 * Модели API-слоя: тела запросов и тела ответов.
 *
 * <h2>Зачем модели вообще</h2>
 * Альтернатива — читать ответ точечно: {@code response.jsonPath().getString("user.first_name")}.
 * Такой путь это СТРОКА, которую компилятор не проверяет: опечатка даёт не ошибку, а тихий {@code null}.
 * Модель переносит соответствие «ключ JSON → поле Java» в одно место — в класс,
 * после чего обращение к данным проверяет компилятор.
 *
 * <h2>Главное, что здесь неочевидно: два РАЗНЫХ вида моделей</h2>
 * Классы этого пакета делятся на две группы, и путать их нельзя:
 *
 * <h3>1. Конверт (Container) — описывает ВСЁ тело ответа целиком</h3>
 * Стенд заворачивает полезные данные в оболочку с кодом результата:
 * <pre>
 * {"responseCode": 200, "user": { ... } }
 *  └── конверт ────────────┴── полезная нагрузка
 * </pre>
 * {@code response.as(Class)} применяется ВСЕГДА К КОРНЮ тела. Поэтому первым классом
 * обязан быть конверт: если передать сюда модель вложенного объекта, совпадений
 * не найдётся ни одного и все поля молча окажутся {@code null}.
 *
 * <h3>2. Вложенная модель — описывает один уровень ВНУТРИ конверта</h3>
 * Сколько уровней вложенности в теле — столько классов в цепочке.
 *
 * <h2>Карта: какой класс какому уровню JSON соответствует</h2>
 * <pre>
 * GET /api/getUserDetailByEmail
 * {"responseCode":200, "user":{"id":1,"first_name":"Den", ...}}
 *  └─ ResponseAccountContainerModel   (конверт)
 *            └─ user ─────────────────→ AccountResponseModel   (вложенная)
 *
 * GET /api/productsList
 * {"responseCode":200, "products":[{"id":1,"category":{"usertype":{"usertype":"Women"}}}]}
 *  └─ ResponseProductContainerModel   (конверт)
 *            └─ products[] ───────────→ ProductResponseModel   (вложенная, СПИСОК)
 *                     └─ category ────→ CategoryModel          (вложенная)
 *                             └─ usertype → UserTypeModel      (вложенная, 3-й уровень)
 *
 * POST /api/createAccount, PUT /api/updateAccount, DELETE /api/deleteAccount
 * {"responseCode":201, "message":"User created!"}
 *  └─ AccountCommonResponseModel      (конверт, полезной нагрузки нет вовсе)
 * </pre>
 *
 * <h2>Ловушка в именах — читать внимательно</h2>
 * {@code ResponseAccountContainerModel} и {@code AccountResponseModel} — это НЕ одно и то же
 * и не варианты одного. Первый — конверт (всё тело), второй — то, что лежит внутри него
 * под ключом {@code user}. Слова те же, порядок разный, смысл противоположный по уровню.
 * Признак конверта — слово {@code Container} в имени и поле {@code responseCode} внутри.
 *
 * <h2>Почему конвертов ТРИ, а не один общий</h2>
 * Один общий конверт с полями {@code user} + {@code products} + {@code message} технически
 * работал бы: недостающее в JSON поле модели просто остаётся {@code null}. Отказались
 * сознательно — модель должна быть ОПИСАНИЕМ КОНТРАКТА конкретного эндпоинта, а не мешком
 * для всего, что теоретически может прийти:
 * <ul>
 *   <li>{@code user} и {@code products} взаимоисключающи — для любого эндпоинта
 *       одно из них структурно не может быть заполнено;</li>
 *   <li>терялась бы проверка: ответ с {@code user} там, где ждали {@code products},
 *       разобрался бы УСПЕШНО в объект с {@code products == null}, и узнали бы мы об этом
 *       на ассерте или на NPE, а не на разборе тела.</li>
 * </ul>
 * Ощущение дублирования при этом верное — три почти одинаковых конверта это реальная цена.
 * Настоящее решение — обобщённый {@code ApiResponse<T>} с {@code TypeRef}; отложено
 * отдельной задачей, потому что это решение уровня слоя, а не одного эндпоинта.
 *
 * <h2>Почему у конвертов есть поле {@code message}, хотя в успешном ответе его нет</h2>
 * У этих эндпоинтов ДВА разных тела. Успех: {@code {"responseCode":200,"user":{...}}}.
 * Ошибка: {@code {"responseCode":404,"message":"Account not found..."}} — ключа {@code user}
 * нет вовсе, зато есть {@code message}.
 * <p>
 * Десериализация выполняется ДО проверки {@code responseCode}. Значит, если конверт не
 * описывает ключи ветки ошибки, то на любом не-200 разбор разваливается внутри Jackson —
 * и проверка кода ответа становится НЕДОСТИЖИМОЙ. Правило: если у эндпоинта два тела,
 * конверт обязан описывать объединение их ключей.
 *
 * <h2>Почему модели ответов помечены {@code @Data}, а {@code AccountModel} — нет</h2>
 * Модель ЗАПРОСА ({@link api.models.AccountModel}) собирается нашим кодом: ей нужен
 * {@code @Builder} и геттеры, сеттеры не нужны и вредны.
 * Модель ОТВЕТА собирает Jackson, и ему требуется, чем заполнять объект. Комбинация
 * {@code @Builder + @Getter} для ответа НЕ РАБОТАЕТ вовсе:
 * {@code InvalidDefinitionException: Cannot construct instance ... no Creators, like default constructor, exist}.
 * Подходят {@code @Data} (конструктор без аргументов + сеттеры) либо {@code @Builder + @Jacksonized}.
 * Взят {@code @Data} — так же разведено в боевом проекте-референсе.
 *
 * <h2>Почему {@code @JsonProperty} стоит не везде</h2>
 * Jackson сопоставляет имя поля Java с ключом JSON ТОЧНО. Аннотация нужна только там, где
 * написание расходится, и служит меткой «здесь имя другое»:
 * <ul>
 *   <li>{@code first_name → firstName} — snake_case;</li>
 *   <li>{@code usertype → userType} — РЕГИСТР: расхождением считается любое несовпадение,
 *       не только подчёркивания;</li>
 *   <li>{@code user → accountResponseModel} — поле намеренно названо иначе, чем ключ.</li>
 * </ul>
 * Где имена совпадают ({@code id}, {@code name}, {@code price}, {@code brand}) — аннотации нет,
 * и это осознанно: сплошная разметка перестала бы что-либо означать.
 *
 * <h2>Что ловит Jackson, а что обязан ловить тест</h2>
 * Используется Jackson 2.x, где {@code FAIL_ON_UNKNOWN_PROPERTIES} включён по умолчанию
 * (в Jackson 3 — выключен, и та же ошибка стала бы тихой: все поля {@code null} без сообщения).
 * Строгий режим проверяет ФОРМУ контракта: пришёл незнакомый ключ — падение с точным текстом.
 * <p>
 * Чего он не поймает: перестановки двух полей ОДНОГО типа. Если у {@code price} и {@code brand}
 * (оба {@code String}) перепутать {@code @JsonProperty}, оба ключа останутся известными,
 * исключения не будет, значения молча уедут не туда. Это ловится только ассертом на известное
 * значение — и ловится один раз, в момент написания модели.
 */
